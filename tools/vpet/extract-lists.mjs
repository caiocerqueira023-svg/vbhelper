function expectedFromJs(model, decoded, responseLines) {
    if (!decoded) fail(`recovered JS decoder rejected the synthetic ${model} vector`);
    if (decoded.ignorar) fail(`synthetic ${model} vector decoded as "ignorable"`);

    const position = (value) => (value === null || value === undefined || Number.isNaN(value) ? '-' : String(value));
    let checksumValid;
    if (model === 'dmx') checksumValid = decoded.n === 6;
    else if (model === 'dmc') checksumValid = decoded.n === 1;
    else checksumValid = decoded.valido === true;

    return {
        model,
        version: decoded.version,
        index: decoded.indice,
        name: position(decoded.nombre),
        stage: position(decoded.etapa),
        attribute: position(decoded.attr),
        power: position(decoded.poder),
        checksumValid,
        payloadHex: decoded.hex,
        responseLines,
    };
}

function decodeVectors(lector, listas) {
    const vectors = [];

    const dm20 = dm20Words(listas);
    vectors.push(expectedFromJs('dm20', lector.decDM20(packetLines(dm20.words)), packetLines(dm20.words)));

    const pen20 = pen20Words(listas);
    vectors.push(expectedFromJs('pen20', lector.decPen20(packetLines(pen20.words)), packetLines(pen20.words)));

    const penz = penzWords(listas);
    vectors.push(expectedFromJs('penz', lector.decPenZ(packetLines(penz.words)), packetLines(penz.words)));

    const dmx = dmxWords(listas);
    if (dmx.listName !== 'x2') fail(`unexpected DMX list ${dmx.listName}`);
    vectors.push(expectedFromJs('dmx', lector.decDMX(packetLines(dmx.words)), packetLines(dmx.words)));

    const dmc = dmcVector(listas);
    vectors.push(expectedFromJs('dmc', lector.decDMC(dmc.hex), dmc.lines));

    const dmcVip = dmcVipVector(listas);
    if (dmcVip) vectors.push(expectedFromJs('dmc', lector.decDMC(dmcVip.hex), dmcVip.lines));

    const dmcVipWarning = dmcVipWarningVector(listas);
    if (dmcVipWarning) vectors.push(expectedFromJs('dmc', lector.decDMC(dmcVipWarning.hex), dmcVipWarning.lines));

    const penc = pencVector(listas);
    vectors.push(expectedFromJs('penc', lector.decPenC(penc.hex), penc.lines));

    for (const vector of vectors) {
        if (vector.name === '-') fail(`synthetic ${vector.model} vector resolved to an unknown name`);
        if (!vector.checksumValid) fail(`synthetic ${vector.model} vector is not checksum-valid`);
        if (!vector.payloadHex) fail(`synthetic ${vector.model} vector has no payload hex`);
    }
    return vectors;
}

/**
 * Sanity-checks the DigiROM builders against a local reimplementation of the lector.js
 * formulas. The golden file always uses the JS output; this only catches accidental drift in
 * the formulas while the script is being maintained.
 */
function verifyRomBuilders(lector) {
    const dmcRival = 'C1-47444C4300000000000B007300019406-47444C4300020002000000000000938B';
    const pencRival = 'C1-4744447000000000000B007300018C33-47444470000200020000000000008BB8';
    const roto2 = (command) => {
        const match = /^C1-([0-9A-F]{32})-([0-9A-F]{32})$/i.exec(command);
        if (!match) fail(`cannot parse color rival command: ${command}`);
        const tail = (parseInt(match[2].slice(28), 16) ^ 0xffff).toString(16).toUpperCase().padStart(4, '0');
        return `C1-${match[1]}-${match[2].slice(0, 28)}${tail}`;
    };
    const expected = {
        dm20: (version) => {
            const words = [0x0301, 0x0d0f, ((version & 0xf) << 4) | 0xe, (2 << 6) | 0xe,
                (1 << 10) | (26 << 4) | 0xe, (18 << 4) | 0xe, 0xe, 0xe, 0xe, 0x000e];
            return `V2-${withRomChecksum(words, 16).map(hex4).join('-')}`;
        },
        dmx: (version) => `V2-23${(version & 0xf).toString(16).toUpperCase()}E-AA2E-560E-182E-0CAE-103E`,
        pen20: (version) => {
            const words = [((version & 0xf) << 4) | 0xe, (118 << 6) | 0xe, 0xe, 0xe, (16 << 4) | 0xe,
                0xe, 0xe, 0xe, 0xe, 0x000e];
            return `V2-${withRomChecksum(words, 12).map(hex4).join('-')}`;
        },
        penz: (version) => {
            const words = [0x030e | ((version & 0xf) << 4), 0x212e, 0x288e, 0x182e, 0x018e, 0x000e];
            return `V2-${withRomChecksum(words, 16).map(hex4).join('-')}`;
        },
        dmc: () => roto2(dmcRival),
        penc: () => roto2(pencRival).replace(/^C1-/, 'C2-'),
    };
    for (const model of MODELS) {
        for (let version = 0; version <= 15; version += 1) {
            const actual = lector[model.romFn](version);
            const expectedCommand = expected[model.wireKey](version);
            if (actual !== expectedCommand) {
                fail(`DigiROM drift for ${model.wireKey} v${version}:\n  js:       ${actual}\n  expected: ${expectedCommand}`);
            }
        }
    }
}

function buildRomVectors(lector) {
    const lines = [];
    for (const model of MODELS) {
        for (let version = 0; version <= 15; version += 1) {
            lines.push(`rom\t${model.wireKey}\t${version}\t${lector[model.romFn](version)}`);
        }
    }
    return lines;
}

function buildTableVectors(listas) {
    return LIST_KEYS.map((key) => {
        const value = key.startsWith('x') ? listas.x[Number(key.slice(1))] : listas[key];
        if (typeof value !== 'string') fail(`LISTAS.${key} is missing`);
        return `table\t${key}\t${value.split('|').length}`;
    });
}

function buildGoldenContent(lector, listas) {
    const vectors = decodeVectors(lector, listas);
    const header = [
        GOLDEN_HEADER,
        '# Golden vectors for the Kotlin port of the recovered DBT-Link VPet protocol.',
        '# Generated by tools/vpet/extract-lists.mjs from',
        '# analysis/vpet-rea/recovered/lector.js (DBT-Link v18.9 recovered assets).',
        '# Do not edit by hand: regenerate with `node tools/vpet/extract-lists.mjs`.',
        '#',
        '# Lines are tab-separated. Kinds:',
        '#   rom      <model> <version> <command>',
        '#            VpetDigiRom.commandFor(model, version) for versions 0..15 of every model.',
        '#   decode   <model> <version> <index> <name> <stage> <attribute> <power> <checksumValid> <payloadHex>',
        '#            Expected VpetReadResult for the response lines of the next `response` line.',
        '#            Null fields are `-`, checksumValid is 1/0, payloadHex is the original JS hex.',
        '#   response <model> <line>|<line>|...',
        '#            Lines fed to VpetDecoders.decode(model, lines, version); `|` separates lines.',
        '#   table    <name> <slotCount>',
        '#            Number of `|`-separated slots of the list in vpet-lists.txt.',
        '#',
        '# Every decode vector was produced by calling the recovered JavaScript decoder itself, so',
        '# the Kotlin port must reproduce these values exactly.',
        '',
    ];
    const body = [
        ...buildRomVectors(lector),
        ...buildTableVectors(listas),
        ...vectors.flatMap((vector) => [
            `decode\t${vector.model}\t${vector.version}\t${vector.index}\t${vector.name}\t${vector.stage}\t${vector.attribute}\t${vector.power}\t${vector.checksumValid ? 1 : 0}\t${vector.payloadHex}`,
            `response\t${vector.model}\t${vector.responseLines.join('|')}`,
        ]),
    ];
    return { content: [...header, ...body, ''].join('\n'), vectors };
}

// ---------------------------------------------------------------------------
// Output
// ---------------------------------------------------------------------------

function buildListsContent(listas) {
    const lines = [LISTS_HEADER];
    for (const key of LIST_KEYS) {
        const value = key.startsWith('x') ? listas.x[Number(key.slice(1))] : listas[key];
        if (typeof value !== 'string') fail(`LISTAS.${key} is missing or is not a string`);
        if (value.includes('\t') || value.includes('\n') || value.includes('\r')) {
            fail(`LISTAS.${key} contains characters that break the tab-separated format`);
        }
        lines.push(`${key}\t${value}`);
    }
    return `${lines.join('\n')}\n`;
}

function writeOutput(path, content) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, 'utf8');
}

function main() {
    const source = readFileSync(LECTOR_PATH, 'utf8');
    const { json, parsed } = extractListasJson(source);
    const lector = loadLector(source);

    verifyRomBuilders(lector);

    const listsContent = buildListsContent(parsed);
    const golden = buildGoldenContent(lector, parsed);

    writeOutput(LISTS_PATH, listsContent);
    writeOutput(GOLDEN_PATH, golden.content);

    const count = (content, prefix) => content.split('\n').filter((line) => line.startsWith(prefix)).length;
    const counts = {
        LISTAS: JSON.stringify(json).length,
        bytes: Buffer.byteLength(listsContent, 'utf8') + Buffer.byteLength(golden.content, 'utf8'),
    };

    console.log('[vpet-extract] source:', displayPath(LECTOR_PATH));
    console.log(`[vpet-extract] LISTAS JSON: ${counts.LISTAS} chars, keys: ${Object.keys(parsed).join(', ')}`);
    console.log(`[vpet-extract] wrote ${displayPath(LISTS_PATH)}`);
    console.log(`  lists: ${LIST_KEYS.join(', ')}`);
    for (const key of LIST_KEYS) {
        const value = key.startsWith('x') ? parsed.x[Number(key.slice(1))] : parsed[key];
        console.log(`  ${key.padEnd(6)} ${String(value.length).padStart(5)} chars, ${String(value.split('|').length).padStart(4)} slots`);
    }
    console.log(`[vpet-extract] wrote ${displayPath(GOLDEN_PATH)}`);
    console.log(`  rom vectors:      ${count(golden.content, 'rom\t')}`);
    console.log(`  decode vectors:   ${count(golden.content, 'decode\t')}`);
    console.log(`  response vectors: ${count(golden.content, 'response\t')}`);
    console.log(`  table vectors:    ${count(golden.content, 'table\t')}`);
    console.log(`  bytes: ${Buffer.byteLength(listsContent, 'utf8')} (lists) + ${Buffer.byteLength(golden.content, 'utf8')} (golden)`);
    console.log('[vpet-extract] sample ROMs:');
    for (const model of MODELS) {
        console.log(`  ${model.wireKey.padEnd(6)} v0: ${lector[model.romFn](0)}`);
        console.log(`  ${model.wireKey.padEnd(6)} v15: ${lector[model.romFn](15)}`);
    }
}

main();
