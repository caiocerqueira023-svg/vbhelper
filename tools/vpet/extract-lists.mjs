/**
 * Returns the source slice of the `const LISTAS = {...};` literal by scanning for the
 * balanced closing brace (strings are skipped so braces inside names cannot confuse it).
 */
function extractListasJson(source) {
    const marker = 'const LISTAS = ';
    const markerIndex = source.indexOf(marker);
    if (markerIndex < 0) fail('LISTAS literal not found in lector.js');
    const start = source.indexOf('{', markerIndex);
    if (start < 0) fail('LISTAS object start not found in lector.js');

    let depth = 0;
    let inString = false;
    let escaped = false;
    let end = -1;
    for (let i = start; i < source.length; i += 1) {
        const char = source[i];
        if (inString) {
            if (escaped) escaped = false;
            else if (char === '\\') escaped = true;
            else if (char === '"') inString = false;
            continue;
        }
        if (char === '"') {
            inString = true;
        } else if (char === '{') {
            depth += 1;
        } else if (char === '}') {
            depth -= 1;
            if (depth === 0) {
                end = i;
                break;
            }
        }
    }
    if (end < 0) fail('LISTAS object is not balanced');
    const json = source.slice(start, end + 1);
    let parsed;
    try {
        parsed = JSON.parse(json);
    } catch (error) {
        fail(`LISTAS is not valid JSON: ${error.message}`);
    }
    return { json, parsed };
}

/**
 * Evaluates the recovered lector.js and returns `window.LECTOR`. The sandbox only provides
 * the browser globals the script touches while loading; its timers/localStorage are never
 * exercised because this script calls the pure `rom*`/`dec*` helpers only.
 */
function loadLector(source) {
    const sandbox = {
        window: {},
        console,
        JSON,
        Math,
        Date,
        localStorage: {
            getItem: () => null,
            setItem: () => {},
            removeItem: () => {},
        },
        setTimeout: () => 0,
        clearTimeout: () => {},
        setInterval: () => 0,
        clearInterval: () => {},
    };
    vm.createContext(sandbox);
    vm.runInContext(source, sandbox, { filename: 'lector.js' });
    const lector = sandbox.window.LECTOR;
    if (!lector) fail('lector.js did not define window.LECTOR');
    for (const model of MODELS) {
        for (const fn of [model.romFn, model.decFn]) {
            if (typeof lector[fn] !== 'function') fail(`lector.js does not expose ${fn}()`);
        }
    }
    return lector;
}

// ---------------------------------------------------------------------------
// Protocol helpers (kept intentionally small: the golden vectors themselves come from JS)
// ---------------------------------------------------------------------------

const hex4 = (value) => ('000' + ((value & 0xffff).toString(16).toUpperCase())).slice(-4);

const nibbleSum = (words) =>
    words.reduce(
        (total, word) =>
            total + ((word >> 12) & 0xf) + ((word >> 8) & 0xf) + ((word >> 4) & 0xf) + (word & 0xf),
        0,
    );

/**
 * Reimplements the lector.js response checksum: make the nibble sum of a synthetic packet
 * set congruent to `modulus` (0 for DM20, 12 for Pen20, 8 for PenZ), which is what decoders
 * require from a legitimate VPet answer. The last word is replaced, not OR-ed; `lowNibble`
 * keeps the 0xE marker that PenZ/DMX answer packets carry (the session filters on it).
 */
function withResponseChecksum(words, modulus, lowNibble = 0) {
    const result = words.slice();
    const lastIndex = result.length - 1;
    result[lastIndex] = lowNibble & 0xf;
    const digit = (((modulus - (nibbleSum(result) % 16)) % 16) + 16) % 16;
    result[lastIndex] |= (digit & 0xf) << 12;
    return result;
}

/**
 * Reimplements the lector.js DigiROM checksum verbatim: the last word already carries a 0xE
 * low nibble, the correction digit is OR-ed into its high nibble and the sum is intentionally
 * left one step off (that is what makes the VPet dump its data instead of starting a battle).
 * `formulaBase` is 16 for DM20/PenZ and 12 for Pen20, matching their `rom*` functions.
 */
function withRomChecksum(words, formulaBase) {
    const result = words.slice();
    const lastIndex = result.length - 1;
    const digit = ((((formulaBase - (nibbleSum(result) % 16)) % 16) + 16) % 16 + 1) & 0xf;
    result[lastIndex] |= (digit & 0xf) << 12;
    return result;
}

const packetLines = (words) => words.map((word) => `r:${hex4(word)}`);

const blockHex = (words) => words.map(hex4).join('');

function readFlatRow(entry) {
    if (!entry) return null;
    const parts = entry.split('~');
    if (!parts[0]) return null;
    const stage = parts[1] === undefined || parts[1] === '' ? null : Number(parts[1]);
    const attribute = parts[2] === undefined || parts[2] === '' ? null : Number(parts[2]);
    if (!Number.isFinite(stage) || !Number.isFinite(attribute)) return null;
    return { name: parts[0], stage, attribute };
}

function pickIndex(rawList, preferred) {
    const slots = rawList.split('|');
    if (preferred > 0 && preferred < slots.length && readFlatRow(slots[preferred])) return preferred;
    for (let index = 1; index < slots.length; index += 1) {
        const row = readFlatRow(slots[index]);
        if (row) return index;
    }
    fail('no usable index in list');
}

function indexedEntry(rawList, index) {
    const row = readFlatRow(rawList.split('|')[index]);
    if (!row) fail(`no table entry at index ${index}`);
    return row;
}

function keyedValue(rawList) {
    const map = new Map();
    for (const part of rawList.split('|')) {
        const separator = part.indexOf('=');
        if (separator > 0) map.set(part.slice(0, separator), part.slice(separator + 1));
    }
    return map;
}

function keyedEntry(row) {
    const parts = row.split('~');
    return {
        name: parts[0] || null,
        stage: parts[1] === undefined || parts[1] === '' ? null : Number(parts[1]),
        attribute: parts[2] === undefined || parts[2] === '' ? null : Number(parts[2]),
    };
}

// ---------------------------------------------------------------------------
// Synthetic packet sets (each one is decoded by the recovered JS to build the golden value)
// ---------------------------------------------------------------------------

/** DM20: 10x16-bit words, nibble sum % 16 must be 0. */
function dm20Words(listas) {
    const version = 3;
    const index = pickIndex(listas.dm20, 4);
    const entry = indexedEntry(listas.dm20, index);
    const attribute = entry.attribute ?? 0;
    const power = 123;
    const words = [
        0x0301,
        0x0d0f,
        ((version & 0xf) << 4) | 0xe,
        (index << 6) | (attribute << 4) | 0xe,
        0x000e,
        (power << 4) | 0xe,
        0x000e,
        0x000e,
        0x000e,
        0x0000,
    ];
    return { model: 'dm20', version, index, words: withResponseChecksum(words, 0), lines: null };
}

/** Pen20: 10x16-bit words, nibble sum % 16 must be 12, version 6..9, copy code 0. */
function pen20Words(listas) {
    const version = 6;
    const index = pickIndex(listas.pen20, 18);
    const entry = indexedEntry(listas.pen20, index);
    const attribute = entry.attribute ?? 1;
    const power = 123;
    const copy = 0;
    const words = [
        ((version & 0xf) << 4) | 0xe,
        (index << 6) | (attribute << 4) | 0xe,
        0x000e,
        0x000e,
        (power << 4) | 0xe,
        (copy << 14) | 0x000e,
        0x0000,
        0x0000,
        0x0000,
        0x0000,
    ];
    return { model: 'pen20', version, index, words: withResponseChecksum(words, 12), lines: null };
}

/** PenZ: 6x16-bit words, nibble sum % 16 must be 8, version 6..11. */
function penzWords(listas) {
    const version = 6;
    const index = pickIndex(listas.z1, 10);
    const entry = indexedEntry(listas.z1, index);
    const attribute = entry.attribute ?? 2;
    const power = 77;
    const stageVpet = 3;
    const words = [
        ((version & 0xf) << 4) | 0xe,
        (stageVpet << 13) | (index << 6) | (attribute << 4) | 0xe,
        0x000e,
        0x000e,
        (power << 4) | 0xe,
        0x0000,
    ];
    return { model: 'penz', version, index, words: withResponseChecksum(words, 8, 0xe), lines: null };
}

/** DMX: 6x16-bit words that all end in the 0xE low nibble (the decoder filters on it). */
function dmxWords(listas) {
    const version = 4;
    const listName = `x${Math.floor(version / 2)}`;
    const index = pickIndex(listas.x[Math.floor(version / 2)], 5);
    const entry = indexedEntry(listas.x[Math.floor(version / 2)], index);
    const attribute = entry.attribute ?? 2;
    const stageVpet = entry.stage ?? 1;
    const words = [
        ((version & 0xf) << 4) | 0xe,
        (stageVpet << 13) | (index << 6) | (attribute << 4) | 0xe,
        0x000e,
        0x000e,
        0x000e,
        0x000e,
    ];
    return { model: 'dmx', version, index, words, lines: null, listName };
}

/**
 * DMC: one 16-byte block (8 words), no checksum. Word 3 is `version - 1` for Ver.1-5, so the
 * synthetic block reports version 1 and an index that exists in the recovered DMC table.
 */
function dmcVector(listas) {
    const map = keyedValue(listas.dmc);
    const keys = [...map.keys()];
    if (keys.length === 0) fail('DMC table is empty');
    const key = keys.find((candidate) => candidate.startsWith('01-')) ?? keys[0];
    const [versionText, indexText] = key.split('-');
    const version = Number(versionText);
    const index = Number(indexText);
    const power = 100;
    const words = [0x4744, 0x4c43, 0, version - 1, index, power, 0, 0];
    return {
        model: 'dmc',
        version,
        index,
        hex: blockHex(words),
        lines: [`r:${blockHex(words)}`],
    };
}

/**
 * DMC "VIP" fallback (matching version): index 17 only exists in the VIP versions 17/19 plus
 * the regular version 3 table. Reporting version 1 has no direct `01-17` key, so the recovered
 * decoder must resolve it through the VIP mapping (version 1 is listed for `17-17`).
 */
function dmcVipVector(listas) {
    const map = keyedValue(listas.dmc);
    if (!map.has('17-17')) return null;
    const version = 1;
    const index = 17;
    const words = [0x4744, 0x4c43, 0, version - 1, index, 100, 0, 0];
    return {
        model: 'dmc',
        version,
        index,
        hex: blockHex(words),
        lines: [`r:${blockHex(words)}`],
    };
}

/**
 * DMC "VIP" fallback (version mismatch warning): index 18 exists only in VIP versions 18
 * (`18-18` maps to versions 3/4). Reporting version 1 forces the decoder to pick that key while
 * recording the "number does not fit the version" warning.
 */
function dmcVipWarningVector(listas) {
    const map = keyedValue(listas.dmc);
    if (!map.has('18-18')) return null;
    const version = 1;
    const index = 18;
    const words = [0x4744, 0x4c43, 0, version - 1, index, 100, 0, 0];
    return {
        model: 'dmc',
        version,
        index,
        hex: blockHex(words),
        lines: [`r:${blockHex(words)}`],
    };
}

/**
 * PenC: one 16-byte block (8 words), word 0..6 sum (mod 0x10000) must equal word 7.
 * Version 6 is encoded as a raw 6 (`(rawVersion + 1) % 6` only applies to raw 0..5).
 */
function pencVector(listas) {
    const map = keyedValue(listas.penc);
    const keys = [...map.keys()];
    if (keys.length === 0) fail('PenC table is empty');
    const key = keys.find((candidate) => candidate.startsWith('6-')) ?? keys.find((candidate) => candidate.startsWith('1-')) ?? keys[0];
    const [tableVersionText, indexText] = key.split('-');
    const tableVersion = Number(tableVersionText);
    const index = Number(indexText);
    const rawVersion = tableVersion >= 1 && tableVersion <= 5 ? tableVersion - 1 : tableVersion === 6 ? 6 : 5;
    const words = [0x4744, 0x4470, 1, rawVersion, index, 50, 0, 0];
    words[7] = (words[0] + words[1] + words[2] + words[3] + words[4] + words[5] + words[6]) & 0xffff;
    return {
        model: 'penc',
        version: rawVersion,
        index,
        hex: blockHex(words),
        lines: [`r:${blockHex(words)}`],
    };
}

