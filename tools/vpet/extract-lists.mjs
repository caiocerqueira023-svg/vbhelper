#!/usr/bin/env node
/**
 * Extracts the VPet protocol tables and golden vectors from the recovered DBT-Link
 * implementation (`analysis/vpet-rea/recovered/lector.js`) so the Kotlin port in
 * `:hardware-vpet` can be pinned against the original JavaScript.
 *
 * Outputs (both committed):
 *
 * 1. `hardware-vpet/src/main/resources/vpet-lists.txt`
 *    First line `#vpet-lists-v1`, then one line per list: `<name>\t<value>`.
 *    Names (in order): dm20, pen20, z1, z2, x0, x1, x2, dmc, penc.
 *    Values are copied verbatim from the `LISTAS` object (the `x` array is flattened into
 *    x0, x1, x2). Flat lists are `name~stage~attribute` entries separated by `|`; the
 *    position is the index the VPet sends. Keyed lists (dmc/penc) are
 *    `key=name~stage~attribute` entries separated by `|`.
 *
 * 2. `hardware-vpet/src/test/resources/vpet-golden.txt`
 *    Golden vectors generated by evaluating the original lector.js in a Node VM sandbox and
 *    calling its own `rom*`/`dec*` functions, so they are byte-for-byte authoritative.
 *    The file is tab-separated with a documented header; the line kinds are:
 *
 *      rom      <model> <version> <command>
 *               VpetDigiRom.commandFor(model, version), versions 0..15 for every model.
 *      decode   <model> <version> <index> <name> <stage> <attribute> <power> <checksumValid> <payloadHex>
 *               Expected VpetReadResult fields for the response in the next `response` line.
 *               Null fields are `-`; checksumValid is 1/0; payloadHex is the JS `hex` value.
 *      response <model> <line>|<line>|...
 *               Response lines (as received from the adapter) fed to
 *               VpetDecoders.decode(model, lines, version). `|` separates lines, which never
 *               contain `|` themselves.
 *      table    <name> <slotCount>
 *               Number of `|`-separated slots in the recovered list (index space size).
 *
 * Usage: `node tools/vpet/extract-lists.mjs`
 */

